namespace Calculadora;

public class Calculadora
{
    public double Soma(double num1, double num2)
    {
        return num1 + num2;
    }
    
    public int Subtrair(int num1, int num2)
    {
        return num1 - num2;
    }
    
    public int Dividir(int num1, int num2)
    {
        return num1 / num2;
    }
}